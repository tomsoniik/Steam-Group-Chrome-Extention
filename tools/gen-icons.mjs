// Regenerates src/content/icons.js from @phosphor-icons/core (MIT).
// Usage: npm i --no-save @phosphor-icons/core@2.1.1 && node tools/gen-icons.mjs [path/to/node_modules]
import { readFileSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';
const nm = process.argv[2] || 'node_modules';
const want = {
  pin: 'bold/push-pin-bold', pinFill: 'fill/push-pin-fill', signOut: 'bold/sign-out-bold',
  check: 'bold/check-bold', warn: 'bold/warning-circle-bold', plus: 'bold/plus-bold',
  clock: 'bold/clock-bold', retry: 'bold/arrow-clockwise-bold', filter: 'bold/funnel-simple-bold',
  sort: 'bold/sort-ascending-bold', dup: 'bold/copy-simple-bold', more: 'bold/arrow-down-bold', lock: 'bold/lock-simple-bold', search: 'bold/magnifying-glass-bold', users: 'bold/users-three-bold', gear: 'bold/gear-six-bold', caretLeft: 'bold/caret-left-bold', caretRight: 'bold/caret-right-bold', x: 'bold/x-bold', tag: 'bold/tag-bold', arrowUpRight: 'bold/arrow-up-right-bold',
};
const out = Object.entries(want).map(([k, f]) => {
  const svg = readFileSync(join(nm, '@phosphor-icons/core/assets', `${f}.svg`), 'utf8');
  return `  ${k}: '${svg.match(/ d="([^"]+)"/)[1]}',`;
});
writeFileSync('src/content/icons.js', `'use strict';\n\n/** Phosphor icons (bold / fill), MIT. Generated by tools/gen-icons.mjs, do not edit. */\nSGT.ICON_PATHS = {\n${out.join('\n')}\n};\n`);
console.log('icons:', out.length);
