/** Translate key into lang, replacing $1..$9. Falls back to English, then to the key. */
function sgtTranslate(lang, key, subs) {
  let s = (SGT_STRINGS[lang] && SGT_STRINGS[lang][key]) ?? SGT_STRINGS.en[key] ?? key;
  if (subs) subs.forEach((v, i) => { s = s.split('$' + (i + 1)).join(v); });
  return s;
}
